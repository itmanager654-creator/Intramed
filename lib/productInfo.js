export function productInfo(name, category) {
  const hit = ENTRIES.find((e) => e.re.test(name) && (!e.cat || e.cat === category));
  const fill = (s) => s.replaceAll('{n}', name);
  if (hit) return { kind: hit.kind, what: fill(hit.what), use: fill(hit.use), how: fill(hit.how || '') };
  const [kind, desc, use] = FALLBACK[category] || ['medical device', 'a sterile, single-use medical device', 'It is used in hospital procedures under the direction of a qualified physician.'];
  return { kind, what: `${name} is ${desc}.`, use, how: '' };
}

